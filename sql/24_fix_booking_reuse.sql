-- إزالة القيد القديم (الصارم)
alter table public.mentor_bookings drop constraint if exists mentor_bookings_slot_id_key;

-- استبداله بفهرس فريد جزئي: يمنع تكرار الحجز النشط فقط،
-- ويسمح بوجود أكثر من حجز "ملغى" على نفس الموعد (سجل تاريخي)
create unique index if not exists mentor_bookings_active_slot_uidx
  on public.mentor_bookings(slot_id)
  where status <> 'cancelled';

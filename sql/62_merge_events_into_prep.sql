-- ============================================================
-- دمج "الفعاليات والحضور" مع "جلسات التحضير" بمفهوم واحد
-- ============================================================
-- يُطبّق بعد 61_facilitator_role.sql
--
-- السبب: الجدولان كانا شبه متطابقين بنيويًا (عنوان، تاريخ، موقع،
-- حضور)، والفعاليات ما كانت تظهر للمشارك إطلاقًا. الدمج يبسّط
-- النظام لمفهوم واحد واضح، مع الحفاظ على القدرة على التمييز
-- بينهم بالتقارير عبر حقل تصنيف جديد.
-- ============================================================

-- ------------------------------------------------------------
-- 1. إضافة حقل التصنيف لجدول الجلسات
-- ------------------------------------------------------------
alter table public.prep_sessions add column if not exists session_type text not null default 'prep'
  check (session_type in ('prep', 'event'));

comment on column public.prep_sessions.session_type is 'prep = جلسة تحضيرية، event = فعالية رئيسية بيوم الهاكثون';

-- ------------------------------------------------------------
-- 2. ترحيل بيانات "الفعاليات" الموجودة لجدول الجلسات
--    (بدون مسار محدد = تظهر لكل المشاركين، بالضبط زي سلوكها الأصلي)
-- ------------------------------------------------------------
insert into public.prep_sessions (title, description, session_date, location, session_type, track_id)
select title, description, event_date, location, 'event', null
from public.events
on conflict do nothing;

-- ------------------------------------------------------------
-- 3. ترحيل سجلات الحضور المرتبطة (مطابقة بالعنوان والتاريخ
--    بما إن معرّفات الفعاليات القديمة تختلف عن الجلسات الجديدة)
-- ------------------------------------------------------------
insert into public.prep_attendance (session_id, user_id, checked_in_at)
select ps.id, ea.user_id, ea.scanned_at
from public.event_attendance ea
join public.events e on e.id = ea.event_id
join public.prep_sessions ps on ps.title = e.title and ps.session_date = e.event_date and ps.session_type = 'event'
on conflict (session_id, user_id) do nothing;

-- ------------------------------------------------------------
-- 4. تحديث دالة تسجيل الحضور عبر QR — نفس الدالة تخدم النوعين
--    الآن (dala واحدة بدل دالتين منفصلتين)
-- ------------------------------------------------------------
-- (record_attendance الحالية تكفي؛ ما نحتاج دالة منفصلة للفعاليات بعد اليوم)

-- ------------------------------------------------------------
-- 5. الجدولان القديمان يبقيان كنسخة احتياطية (بدون حذف) —
--    ما يُستخدمان بالكود بعد الآن، تقدر تحذفهم يدويًا لاحقًا
--    بعد التأكد من صحة الترحيل أعلاه
-- ------------------------------------------------------------

-- تحقق من نجاح الترحيل
select session_type, count(*) as عدد_الجلسات
from public.prep_sessions
group by session_type;
